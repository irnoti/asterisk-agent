#!/usr/bin/env bash
# Generates the SQL for Asterisk's PJSIP realtime tables (ps_*) for one Asterisk version, using Asterisk's own alembic migrations
# (contrib/ast-db-manage) in offline mode: no database is contacted. The result is what pjsip-webrtc-setup.sh loads, so a PBX needs
# neither python3 nor internet access to create its tables.
#
#   scripts/gen-pjsip-schema.sh 16.7.0 [OUT_DIR]        # writes OUT_DIR/ps-schema-16.7.0.sql (default: scripts/pjsip-schema)
#   AST_SOURCE=/path/to/asterisk-src scripts/gen-pjsip-schema.sh 16.7.0   # use a source tree instead of fetching the tag
#
# Needs git (fetches only contrib/ast-db-manage of the tag from github.com/asterisk/asterisk) and python 3.8-3.11
# (the migrations need SQLAlchemy 1.4, which does not run on newer pythons).
set -euo pipefail

ver="${1:?usage: gen-pjsip-schema.sh ASTERISK_VERSION [OUT_DIR]}"
here="$(cd "$(dirname "$0")" && pwd)"
out="${2:-$here/pjsip-schema}"
[[ "$ver" =~ ^[0-9]+(\.[0-9]+){1,3}$ ]] || { echo "bad version: $ver" >&2; exit 1; }
work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT

py=""
for c in python3.11 python3.10 python3.9 python3.8; do command -v "$c" >/dev/null && { py="$c"; break; }; done
[ -n "$py" ] || { echo "need python 3.8-3.11 (SQLAlchemy 1.4 does not run on newer versions)" >&2; exit 1; }

src="${AST_SOURCE:-}"
if [ -z "$src" ]; then
  src="$work/asterisk"
  GIT_LFS_SKIP_SMUDGE=1 git clone -q --filter=blob:none --no-checkout --depth 1 --branch "$ver" https://github.com/asterisk/asterisk "$src"
  git -C "$src" sparse-checkout set contrib/ast-db-manage
  GIT_LFS_SKIP_SMUDGE=1 git -C "$src" checkout -q
fi
mig="$src/contrib/ast-db-manage"
[ -f "$mig/config.ini.sample" ] || { echo "$mig/config.ini.sample not found" >&2; exit 1; }

"$py" -m venv "$work/venv"
"$work/venv/bin/pip" -q install 'alembic<1.8' 'sqlalchemy<1.5' pymysql >/dev/null
sed 's#^sqlalchemy.url.*#sqlalchemy.url = mysql+pymysql://x:x@localhost/x#' "$mig/config.ini.sample" >"$work/config.ini"

mkdir -p "$out"
dest="$out/ps-schema-$ver.sql"
{
  echo "-- Asterisk $ver: realtime tables (ps_*, queues, voicemail ...) from contrib/ast-db-manage, alembic offline mode."
  echo "-- Generated by scripts/gen-pjsip-schema.sh; do not edit. Loaded by scripts/pjsip-webrtc-setup.sh."
  echo
  (cd "$mig" && "$work/venv/bin/alembic" -c "$work/config.ini" upgrade head --sql 2>/dev/null)
} >"$dest"
echo "$dest ($(grep -c 'CREATE TABLE' "$dest") tables, sha256 $(sha256sum "$dest" | cut -d' ' -f1))"
