func TestBundleValidation(t *testing.T) {
	good := file("extensions_irnoti.conf", goodDialplan)
	bad := fileBadSum()
	cases := map[string]api.Bundle{
		"empty":        {},
		"bad name":     {Files: []api.File{file("../etc/passwd", "x")}},
		"upper name":   {Files: []api.File{file("Extensions.conf", "x")}},
		"not conf":     {Files: []api.File{file("run.sh", "x")}},
		"bad checksum": {Files: []api.File{bad}},
		"duplicate":    {Files: []api.File{good, good}},
		"ari creds":    {Files: []api.File{file("ari_irnoti.conf", "[x]\ntype=user\n")}},
		"system call":  {Files: []api.File{file("extensions_irnoti.conf", "[a]\nexten => s,1,System(id)\n")}},
		"huge":         {Files: []api.File{file("extensions_irnoti.conf", strings.Repeat(";x\n", 100_000))}},
	}
	for name, b := range cases {
		if ValidateBundle(b) == nil {
			t.Errorf("%s should be refused", name)
		}
	}
	if err := ValidateBundle(api.Bundle{Files: []api.File{good}}); err != nil {
		t.Errorf("a good bundle was refused: %v", err)
	}
}

func fileBadSum() api.File {
	f := file("extensions_irnoti.conf", goodDialplan)
	f.Sha256 = strings.Repeat("0", 64)
	return f
}

func TestSyncWritesOnlyChangedFilesAndReloadsDialplan(t *testing.T) {
	in, r, ast := newInstaller(t)
	if err := in.Install(context.Background(), bundle()); err != nil {
		t.Fatal(err)
	}
	r.calls = nil
	changed, err := in.Sync(context.Background(), bundle())
	if err != nil || changed || len(r.calls) != 0 {
		t.Fatalf("identical bundle must be a no-op: %v %v %v", changed, err, r.calls)
	}
	next := api.Bundle{Version: "v2", Files: []api.File{file("extensions_irnoti.conf", goodDialplan+"\n; v2\n")}}
	changed, err = in.Sync(context.Background(), next)
	if err != nil || !changed {
		t.Fatalf("changed bundle: %v %v", changed, err)
	}
	if !strings.Contains(read(t, filepath.Join(ast, "irnoti", "extensions_irnoti.conf")), "; v2") {
		t.Error("file not updated")
	}
	if len(r.calls) != 1 || r.calls[0] != "asterisk -rx dialplan reload" {
		t.Errorf("commands = %v", r.calls)
	}
	// a reload that fails restores the previous dialplan
	r.fail = "dialplan reload"
	third := api.Bundle{Version: "v3", Files: []api.File{file("extensions_irnoti.conf", goodDialplan+"\n; v3\n")}}
	if _, err := in.Sync(context.Background(), third); err == nil {
		t.Fatal("expected an error")
	}
	if got := read(t, filepath.Join(ast, "irnoti", "extensions_irnoti.conf")); !strings.Contains(got, "; v2") || strings.Contains(got, "; v3") {
		t.Errorf("rollback failed: %q", got)
	}
}

func TestUninstallLeavesTheRestAlone(t *testing.T) {
	in, _, ast := newInstaller(t)
	os.WriteFile(filepath.Join(ast, "extensions.conf"), []byte("[default]\nexten => 1,1,NoOp()\n"), 0o644)
	if err := in.Install(context.Background(), bundle()); err != nil {
		t.Fatal(err)
	}
	if err := in.Uninstall(context.Background(), true); err != nil {
		t.Fatal(err)
	}
	if got := read(t, filepath.Join(ast, "extensions.conf")); got != "[default]\nexten => 1,1,NoOp()\n" {
		t.Errorf("extensions.conf = %q", got)
	}
	for _, p := range []string{filepath.Join(ast, "irnoti"), in.ConfigPath, in.UnitPath} {
		if _, err := os.Stat(p); err == nil {
			t.Errorf("%s should be gone", p)
		}
	}
}

func TestManagedBlocks(t *testing.T) {
	c := UpsertBlock("a\n", "x", "one")
	c = UpsertBlock(c, "x", "two")
	if strings.Count(c, "BEGIN") != 1 || !strings.Contains(c, "two") || strings.Contains(c, "one") {
		t.Errorf("upsert: %q", c)
	}
	if got := RemoveBlock(c, "x"); got != "a\n" {
		t.Errorf("remove: %q", got)
	}
	if got := RemoveBlock("keep\n", "x"); got != "keep\n" {
		t.Errorf("remove on nothing: %q", got)
	}
}
