type fakeRunner struct {
	calls []string
	fail  string // a substring of the command that should fail
}

func (f *fakeRunner) Run(_ context.Context, name string, args ...string) (string, error) {
	cmd := name + " " + strings.Join(args, " ")
	f.calls = append(f.calls, cmd)
	if f.fail != "" && strings.Contains(cmd, f.fail) {
		return "boom", errors.New("exit 1")
	}
	return "", nil
}

func file(name, content string) api.File {
	sum := sha256.Sum256([]byte(content))
	return api.File{Name: name, Content: content, Sha256: hex.EncodeToString(sum[:])}
}

func bundle() api.Bundle {
	return api.Bundle{Version: "v1", Files: []api.File{file("extensions_irnoti.conf", goodDialplan)}}
}

func newInstaller(t *testing.T) (*Installer, *fakeRunner, string) {
	t.Helper()
	dir := t.TempDir()
	ast := filepath.Join(dir, "asterisk")
	if err := os.MkdirAll(ast, 0o755); err != nil {
		t.Fatal(err)
	}
	r := &fakeRunner{}
	return &Installer{
		Cfg:        config.Config{APIURL: "https://api.example.com", Token: "irna_x", AsteriskDir: ast, ARIUser: "irnoti", App: "irnoti"},
		ConfigPath: filepath.Join(dir, "etc", "agent.json"),
		Runner:     r, Log: slog.New(slog.NewTextHandler(io.Discard, nil)),
		BackupRoot: filepath.Join(dir, "backups"), UnitPath: filepath.Join(dir, "irnoti-asterisk.service"), Binary: "/usr/local/bin/irnoti-asterisk",
		Now:    func() time.Time { return time.Date(2026, 10, 18, 9, 0, 0, 0, time.UTC) },
		Verify: func(context.Context) error { return nil },
	}, r, ast
}

func read(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestInstallFreshServer(t *testing.T) {
	in, r, ast := newInstaller(t)
	if err := in.Install(context.Background(), bundle()); err != nil {
		t.Fatal(err)
	}
	ari := read(t, filepath.Join(ast, "irnoti", "ari_irnoti.conf"))
	if !strings.Contains(ari, "[irnoti]") || !strings.Contains(ari, "password="+in.Cfg.ARIPassword) || in.Cfg.ARIPassword == "" {
		t.Fatalf("ARI user file wrong: %q", ari)
	}
	if st, _ := os.Stat(filepath.Join(ast, "irnoti", "ari_irnoti.conf")); st.Mode().Perm() != 0o640 {
		t.Errorf("the ARI file holds a password, mode is %v", st.Mode().Perm())
	}
	if !strings.Contains(read(t, filepath.Join(ast, "ari.conf")), `#include "irnoti/ari_irnoti.conf"`) {
		t.Error("ari.conf lacks the include")
	}
	if !strings.Contains(read(t, filepath.Join(ast, "http.conf")), "bindaddr=127.0.0.1") {
		t.Error("http.conf should enable the local-only server")
	}
	if !strings.Contains(read(t, filepath.Join(ast, "extensions.conf")), `#include "irnoti/extensions_irnoti.conf"`) {
		t.Error("the dialplan include is missing")
	}
	saved, err := config.Load(in.ConfigPath)
	if err != nil || saved.ARIPassword != in.Cfg.ARIPassword {
		t.Fatalf("agent.json not saved: %v", err)
	}
	if st, _ := os.Stat(in.ConfigPath); st.Mode().Perm() != 0o600 {
		t.Errorf("agent.json holds the token, mode is %v", st.Mode().Perm())
	}
	want := []string{"asterisk -rx module reload http", "asterisk -rx module reload res_ari.so", "asterisk -rx dialplan reload", "systemctl --version", "systemctl daemon-reload", "systemctl enable --now irnoti-asterisk"}
	if strings.Join(r.calls, "|") != strings.Join(want, "|") {
		t.Errorf("commands = %v", r.calls)
	}
	if !strings.Contains(read(t, in.UnitPath), "ExecStart=/usr/local/bin/irnoti-asterisk run --config "+in.ConfigPath) {
		t.Error("unit file wrong")
	}
}

func TestInstallIsIdempotent(t *testing.T) {
	in, _, ast := newInstaller(t)
	for i := 0; i < 2; i++ {
		if err := in.Install(context.Background(), bundle()); err != nil {
			t.Fatal(err)
		}
	}
	for _, f := range []string{"ari.conf", "http.conf", "extensions.conf"} {
		if n := strings.Count(read(t, filepath.Join(ast, f)), "BEGIN irnoti-asterisk"); n != 1 {
			t.Errorf("%s has %d managed blocks", f, n)
		}
	}
}

func TestInstallKeepsExistingContentAndFreePBXLayout(t *testing.T) {
	in, _, ast := newInstaller(t)
	os.WriteFile(filepath.Join(ast, "http.conf"), []byte("[general]\nenabled=yes\nbindaddr=0.0.0.0\nbindport=8089\n"), 0o644)
	os.WriteFile(filepath.Join(ast, "ari.conf"), []byte("[general]\nenabled=yes\n[other]\ntype=user\n"), 0o644)
	os.WriteFile(filepath.Join(ast, "extensions_custom.conf"), []byte("[from-internal-custom]\nexten => 1,1,NoOp()\n"), 0o644)
	os.WriteFile(filepath.Join(ast, "extensions.conf"), []byte("; generated by FreePBX\n"), 0o644)
	if err := in.Install(context.Background(), bundle()); err != nil {
		t.Fatal(err)
	}
	if got := read(t, filepath.Join(ast, "http.conf")); strings.Contains(got, "irnoti") || !strings.Contains(got, "bindport=8089") {
		t.Errorf("a working http.conf must be left alone: %q", got)
	}
	if in.Cfg.ARIURL != "http://127.0.0.1:8089" {
		t.Errorf("ARI url = %s", in.Cfg.ARIURL)
	}
	if !strings.Contains(read(t, filepath.Join(ast, "ari.conf")), "[other]") {
		t.Error("existing ARI users were lost")
	}
	if !strings.Contains(read(t, filepath.Join(ast, "extensions_custom.conf")), `#include "irnoti/extensions_irnoti.conf"`) || strings.Contains(read(t, filepath.Join(ast, "extensions.conf")), "irnoti") {
		t.Error("the include belongs in extensions_custom.conf, not the generated extensions.conf")
	}
}

func TestInstallRollsBackWhenAsteriskRejectsOrARIStaysDown(t *testing.T) {
	for name, tweak := range map[string]func(*Installer, *fakeRunner){
		"reload fails": func(_ *Installer, r *fakeRunner) { r.fail = "dialplan reload" },
		"ari down": func(in *Installer, _ *fakeRunner) {
			in.Verify = func(context.Context) error { return errors.New("401") }
		},
	} {
		t.Run(name, func(t *testing.T) {
			in, r, ast := newInstaller(t)
			orig := "[general]\nenabled=yes\n"
			os.WriteFile(filepath.Join(ast, "ari.conf"), []byte(orig), 0o644)
			tweak(in, r)
			if err := in.Install(context.Background(), bundle()); err == nil || !strings.Contains(err.Error(), "rolled back") {
				t.Fatalf("expected a rollback error, got %v", err)
			}
			if read(t, filepath.Join(ast, "ari.conf")) != orig {
				t.Error("ari.conf was not restored")
			}
			for _, f := range []string{"irnoti/ari_irnoti.conf", "irnoti/extensions_irnoti.conf", "http.conf", "extensions.conf"} {
				if _, err := os.Stat(filepath.Join(ast, f)); err == nil {
					t.Errorf("%s should have been removed", f)
				}
			}
			if _, err := os.Stat(in.ConfigPath); err == nil {
				t.Error("agent.json must not be written for a failed install")
			}
		})
	}
}

