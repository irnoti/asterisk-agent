package setup

import (
	"errors"
	"fmt"
	"net"
	"regexp"
	"strings"

	"github.com/irnoti/asterisk-agent/internal/installer"
)

const (
	AuthRegister = "register" // the provider wants us to register with a user name and password
	AuthIP       = "ip"       // the provider sends calls from fixed IPs and accepts ours without credentials
	AuthNone     = "none"     // configure the trunk later
)

type Trunk struct {
	Name   string // endpoint name; the panel's trunk channel is PJSIP/{number}@<Name>
	Host   string
	Port   int
	Auth   string
	User   string
	Pass   string
	IPs    []string // provider addresses that are allowed to call us; empty = the host itself
	Codecs string
}

type Answers struct {
	Mode     string // connect | full
	APIURL   string
	Token    string
	Method   string // apt | source (full mode, when Asterisk is missing)
	PublicIP string
	NAT      bool
	Trunk    Trunk
	RTPStart int
	RTPEnd   int
	// Softphone is the browser phone (PJSIP over WSS); TLSMode says where TLS ends: "proxy" (CDN/reverse proxy) or "cert" (Asterisk itself).
	Softphone bool
	TLSMode   string
	Domain    string
	Cert, Key string
	Firewall  bool
	// SIPPort is where PJSIP listens (5060 unless chan_sip keeps it); DisableChanSIP unloads chan_sip so PJSIP can have 5060.
	SIPPort        int
	DisableChanSIP bool
}

var (
	hostRe = regexp.MustCompile(`^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$`)
	nameRe = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,40}$`)
)

// ValidHost accepts a DNS name or an IPv4/IPv6 address.
func ValidHost(h string) error {
	if net.ParseIP(h) != nil || hostRe.MatchString(h) {
		return nil
	}
	return fmt.Errorf("%q is not a host name or IP address", h)
}

// ValidSecret rejects what would break an Asterisk config line: ';' starts a comment and a newline ends the value.
func ValidSecret(s string) error {
	if s == "" {
		return errors.New("must not be empty")
	}
	if strings.ContainsAny(s, ";\r\n") {
		return errors.New("must not contain ';' or line breaks")
	}
	return nil
}

func (t Trunk) Validate() error {
	if t.Auth == AuthNone {
		return nil
	}
	if !nameRe.MatchString(t.Name) {
		return fmt.Errorf("trunk name %q: use letters, digits, _ . -", t.Name)
	}
	if err := ValidHost(t.Host); err != nil {
		return err
	}
	if t.Port < 1 || t.Port > 65535 {
		return fmt.Errorf("port %d is out of range", t.Port)
	}
	for _, ip := range t.IPs {
		if net.ParseIP(ip) == nil && !strings.Contains(ip, "/") {
			return fmt.Errorf("%q is not an IP address or CIDR", ip)
		}
	}
	if t.Auth == AuthRegister {
		if t.User == "" || strings.ContainsAny(t.User, ";\r\n ") {
			return errors.New("the trunk user name is empty or has forbidden characters")
		}
		return ValidSecret(t.Pass)
	}
	return nil
}

// PJSIPConf is the managed PJSIP file: our transports and, when given, the trunk. The trunk's endpoint hands inbound calls to irnoti-inbound.
func PJSIPConf(a Answers) string {
	var b strings.Builder
	nat := ""
	if a.NAT && a.PublicIP != "" {
		nat = fmt.Sprintf("external_signaling_address=%[1]s\nexternal_media_address=%[1]s\nlocal_net=10.0.0.0/8\nlocal_net=172.16.0.0/12\nlocal_net=192.168.0.0/16\n", a.PublicIP)
	}
	fmt.Fprintf(&b, "; generated by `irnoti-asterisk setup`\n[irnoti-udp]\ntype=transport\nprotocol=udp\nbind=0.0.0.0:%[3]d\n%[1]s\n[irnoti-tcp]\ntype=transport\nprotocol=tcp\nbind=0.0.0.0:%[3]d\n%[2]s", nat, nat, a.sipPort())
	t := a.Trunk
	if t.Auth == AuthNone || t.Host == "" {
		b.WriteString("\n; no trunk yet: add endpoint/aor/identify sections here (context=irnoti-inbound), then `asterisk -rx \"pjsip reload\"`\n")
		return b.String()
	}
	codecs := t.Codecs
	if codecs == "" {
		codecs = "ulaw,alaw"
	}
	fmt.Fprintf(&b, "\n[%[1]s]\ntype=aor\ncontact=sip:%[2]s:%[3]d\nqualify_frequency=60\n", t.Name, t.Host, t.Port)
	fmt.Fprintf(&b, "\n[%[1]s]\ntype=endpoint\ntransport=irnoti-udp\ncontext=irnoti-inbound\ndisallow=all\nallow=%[2]s\naors=%[1]s\ndirect_media=no\nrtp_symmetric=yes\nforce_rport=yes\nrewrite_contact=yes\ndtmf_mode=rfc4733\n", t.Name, codecs)
	if t.Auth == AuthRegister {
		fmt.Fprintf(&b, "outbound_auth=%[1]s-auth\nfrom_user=%[2]s\n", t.Name, t.User)
		fmt.Fprintf(&b, "\n[%[1]s-auth]\ntype=auth\nauth_type=userpass\nusername=%[2]s\npassword=%[3]s\n", t.Name, t.User, t.Pass)
		fmt.Fprintf(&b, "\n[%[1]s-reg]\ntype=registration\noutbound_auth=%[1]s-auth\nserver_uri=sip:%[2]s:%[4]d\nclient_uri=sip:%[3]s@%[2]s:%[4]d\nretry_interval=60\nexpiration=3600\n", t.Name, t.Host, t.User, t.Port)
	}
	match := t.IPs
	if len(match) == 0 {
		match = []string{t.Host}
	}
	fmt.Fprintf(&b, "\n[%[1]s]\ntype=identify\nendpoint=%[1]s\nmatch=%[2]s\n", t.Name, strings.Join(match, ","))
	return b.String()
}

// RTPOptions are the lines placed under [general] in rtp.conf.
func RTPOptions(a Answers) string {
	return fmt.Sprintf("rtpstart=%d\nrtpend=%d", a.RTPStart, a.RTPEnd)
}

// InsertInGeneral puts the RTP options at the START of [general]: res_rtp_asterisk reads rtpstart/rtpend with a first-match lookup, and packaged
// rtp.conf files already set them (Debian: 10000-20000), so an appended block would be ignored.
func InsertInGeneral(content, tag, body string) string {
	return installer.InsertAtSectionStart(content, "general", tag, body)
}

func (a Answers) sipPort() int {
	if a.SIPPort > 0 {
		return a.SIPPort
	}
	return 5060
}

// SIPPortOf is the port PJSIP listens on.
func SIPPortOf(a Answers) int { return a.sipPort() }

// InsertInSection delegates to the installer, which uses the same placement for http.conf.
func InsertInSection(content, section, tag, body string) string {
	return installer.InsertInSection(content, section, tag, body)
}

// RTPPorts is how many UDP ports the range gives (two per call: RTP and RTCP).
func RTPPorts(a Answers) int { return a.RTPEnd - a.RTPStart + 1 }

func ValidRTP(start, end int) error {
	switch {
	case start < 1024 || end > 65535 || start >= end:
		return errors.New("use a range inside 1024-65535, e.g. 10000-10199")
	case (end-start+1)%2 != 0:
		return errors.New("the range must hold an even number of ports")
	}
	return nil
}
